export const GLYPH_W = 5;
export const GLYPH_H = 7;

/** Measure a string in pixel units at the given letter spacing. */
export function measure(text, spacing = 1) {
  const n = text.length;
  return n === 0 ? 0 : n * GLYPH_W + (n - 1) * spacing;
}
